import os
import re
import json
import logging
import urllib.request
import urllib.error
from typing import List, Optional, Dict, Any

from ai.companion.provider_base import BaseLLMProvider
from ai.companion.schemas import CompanionChatMessage, CompanionContext, CompanionResponse

logger = logging.getLogger("codemind.companion.openai")

class OpenAIProvider(BaseLLMProvider):
    """
    OpenAI is the SOLE conversational intelligence and reasoning brain for Maya.
    Handles all general programming, computer science, code explanation, debugging,
    and multi-turn pedagogical dialogue. Also determines when a concept requires
    a visual animation/diagram to be generated by Gemini.
    """
    def __init__(self):
        # Default to strongest compatible model if OPENAI_MODEL not set; supports GPT-5.6 Sol, gpt-4o, etc.
        self.default_model = os.environ.get("OPENAI_MODEL", "gpt-4o")

    @property
    def provider_name(self) -> str:
        return "openai"

    def is_available(self, api_key: Optional[str] = None) -> bool:
        key = api_key or os.environ.get("OPENAI_API_KEY", "").strip()
        return bool(key)

    def _extract_json_response(self, raw_text: str) -> Dict[str, Any]:
        """
        Robustly extracts JSON from OpenAI responses, handling code blocks,
        leading/trailing text, or direct JSON strings.
        """
        cleaned = raw_text.strip()
        # 1. Direct parse attempt
        try:
            return json.loads(cleaned)
        except Exception:
            pass

        # 2. Extract from markdown code fence ```json ... ```
        fence_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
        if fence_match:
            try:
                return json.loads(fence_match.group(1))
            except Exception:
                pass

        # 3. Find outermost curly braces
        first_brace = cleaned.find("{")
        last_brace = cleaned.rfind("}")
        if first_brace != -1 and last_brace > first_brace:
            try:
                return json.loads(cleaned[first_brace:last_brace + 1])
            except Exception:
                pass

        # 4. Fallback to raw text as message
        return {
            "message": raw_text,
            "expression": "speaking",
            "topics": [],
            "visualization_required": False,
            "visualization_intent": None
        }

    def _execute_api_call(self, api_key: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """
        Executes an HTTP POST to the OpenAI chat completions endpoint with
        graceful retry for parameter compatibility (e.g., max_completion_tokens vs max_tokens, response_format).
        """
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }

        def _do_post(body: Dict[str, Any]) -> Dict[str, Any]:
            data_bytes = json.dumps(body).encode("utf-8")
            req = urllib.request.Request(url, data=data_bytes, headers=headers, method="POST")
            with urllib.request.urlopen(req, timeout=25) as resp:
                return json.loads(resp.read().decode("utf-8"))

        try:
            return _do_post(payload)
        except urllib.error.HTTPError as e:
            error_body = ""
            try:
                error_body = e.read().decode("utf-8")
            except Exception:
                pass
            logger.warning("OpenAI API HTTPError %s: %s", e.code, error_body[:300])

            # Check if model rejects max_tokens in favor of max_completion_tokens (e.g. newer models)
            if "max_completion_tokens" in error_body and "max_tokens" in payload:
                retry_payload = dict(payload)
                retry_payload["max_completion_tokens"] = retry_payload.pop("max_tokens")
                try:
                    return _do_post(retry_payload)
                except Exception as retry_err:
                    logger.warning("Retry with max_completion_tokens failed: %s", retry_err)

            # Check if model rejects response_format json_object
            if "response_format" in error_body and "response_format" in payload:
                retry_payload = dict(payload)
                retry_payload.pop("response_format", None)
                try:
                    return _do_post(retry_payload)
                except Exception as retry_err:
                    logger.warning("Retry without response_format failed: %s", retry_err)

            raise RuntimeError(f"OpenAI API returned status {e.code}: {error_body[:200]}") from e
        except Exception as e:
            logger.warning("OpenAI API call failed: %s (%s)", type(e).__name__, str(e))
            raise RuntimeError(f"OpenAI API call failed: {e}") from e

    def generate_response(
        self,
        user_message: str,
        history: List[CompanionChatMessage],
        context: CompanionContext
    ) -> CompanionResponse:
        api_key = os.environ.get("OPENAI_API_KEY", "").strip()
        if not api_key:
            raise RuntimeError("OPENAI_API_KEY is not configured")

        model = os.environ.get("OPENAI_MODEL", self.default_model)
        bot_name = context.bot_name or "Maya"
        student_name = context.student_name or "Learner"
        lang = context.selected_language or "python"

        system_instruction = (
            f"You are {bot_name}, the world-class AI coding tutor, computer science professor, and companion in CodeMind, "
            f"teaching {student_name}.\n\n"
            "CORE PRINCIPLES & RESPONSIBILITIES:\n"
            "1. UNIVERSAL CS & CODING INTELLIGENCE: You are the ONLY conversational intelligence for Maya. You possess mastery over "
            "all programming languages (C, C++, Java, Python, JavaScript, TypeScript, HTML, CSS, SQL, Go, Rust, Assembly, Bash, etc.) and all Computer Science topics "
            "(Data Structures, Algorithms, Recursion, Pointers, Memory Management, Linked Lists, Trees, Graphs, Sorting, Hashing, "
            "OOP, Operating Systems, DBMS, Computer Networks, Computer Architecture, Digital Logic, Discrete Mathematics, Compilers, Git, "
            "Competitive Programming, LeetCode, System Design, and Debugging).\n"
            "2. NATURAL CONVERSATION & CONTEXT: Seamlessly handle natural conversation, follow-up questions ('why?', 'explain further', "
            "'show me in C', 'what about space complexity?'), clarification of incomplete queries, student corrections, and topic shifts. "
            "Resolve pronouns ('it', 'that', 'my code', 'the previous solution') based on the current conversation turns.\n"
            "3. NO FILLER: Do not start responses with conversational filler ('Sure', 'Certainly', 'Of course', 'Great question'). Jump straight into insightful explanation.\n"
            "4. CODE UNDERSTANDING & WHY-FIRST DEBUGGING: When analyzing code, compiler errors, runtime exceptions, or failed tests: "
            "trace execution, diagnose syntax/logical/runtime/memory errors, analyze edge cases, and explicitly explain WHY the problem occurs. "
            "Do not blindly replace the student's code—guide them to understand and fix their own defect.\n"
            "5. PROBLEM-SOLVING REASONING FRAMEWORK: For coding problems, guide the student's reasoning along this structured path: "
            "UNDERSTAND → OBSERVE → KEY INSIGHT → PATTERN → DATA STRUCTURE / ALGORITHM → APPROACH → PSEUDOCODE → CODE → TEST → OPTIMIZE. "
            "Give progressive hints unless the student explicitly requests the complete solution, in which case provide clean, idiomatic code with full explanation.\n"
            "6. OPTIMIZATION & KEY OBSERVATION: When code works but is suboptimal, analyze: current approach, current time/space complexity, "
            "the performance bottleneck, the KEY OBSERVATION, the improved approach, and why it achieves better complexity. "
            "Prioritize teaching the key observation before providing the optimized code.\n"
            "7. ADAPTIVE STRUCTURED NOTES: When asked for notes, generate clear, structured learning material tailored to the topic "
            "(e.g., Core Concept, Mechanism, Implementation, Complexity Analysis, Common Pitfalls, and Practical Takeaways) without forcing one rigid template.\n"
            "8. DETERMINATION OF VISUALIZATION: You determine whether an explanation genuinely requires or benefits from an interactive data structure or "
            "algorithm visualization (recursion call stack, linked-list pointers, stacks, queues, trees, graphs, sorting, hashing, memory layout, or algorithm execution). "
            "If so, set 'visualization_required': true and describe concisely in 'visualization_intent' what should be visualized (e.g. 'Recursion call stack for factorial(3)' "
            "or 'Linked list pointer reconnection during node deletion'). Otherwise, set 'visualization_required': false.\n"
            "9. OUTPUT FORMAT: Return ONLY a valid JSON object with exactly these keys:\n"
            '   "message": (string, rich markdown explanation with clean syntax-highlighted code blocks),\n'
            '   "expression": (one of: "speaking", "happy", "encouraging", "thinking", "confused", "surprised", "idle"),\n'
            '   "topics": (array of relevant topic strings, e.g. ["Recursion", "Call Stack"] or empty array),\n'
            '   "visualization_required": (boolean, true if this concept warrants an interactive visual animation/diagram),\n'
            '   "visualization_intent": (string or null, concise description of the data structure/algorithm state transitions to visualize)\n'
        )

        context_prompt = (
            f"STUDENT CONTEXT:\n"
            f"- Learner: {student_name}\n"
            f"- Assistant: {bot_name}\n"
            f"- Preferred Language: {lang}\n"
        )
        if context.problem_title:
            context_prompt += f"- Active Problem: {context.problem_title} (ID: {context.problem_id or 'unknown'})\n"
        if context.problem_description:
            context_prompt += f"- Problem Description:\n{context.problem_description}\n"
        if getattr(context, 'input_format', None):
            context_prompt += f"- Input Format:\n{context.input_format}\n"
        if getattr(context, 'output_format', None):
            context_prompt += f"- Output Format:\n{context.output_format}\n"
        if context.constraints:
            context_prompt += f"- Constraints:\n{context.constraints}\n"
        if getattr(context, 'examples', None):
            context_prompt += f"- Examples:\n{context.examples if isinstance(context.examples, str) else json.dumps(context.examples)}\n"
        if context.current_code:
            context_prompt += f"- Editor Code ({lang}):\n```{lang}\n{context.current_code[:2500]}\n```\n"
        if context.last_error:
            context_prompt += f"- Error Diagnostic / Compiler Output:\n{context.last_error[:800]}\n"
        if getattr(context, 'execution_output', None):
            context_prompt += f"- Standard Execution Output:\n{context.execution_output[:800]}\n"
        if getattr(context, 'submission_status', None):
            context_prompt += f"- Submission Status: {context.submission_status}\n"
        if context.failed_test_case:
            tc = context.failed_test_case
            context_prompt += (
                f"- Failed Test Case: Input={tc.get('input', '')} | "
                f"Expected={tc.get('expected_output', '')} | Actual={tc.get('actual_output', '')}\n"
            )

        messages = [
            {"role": "system", "content": system_instruction}
        ]

        # Multi-turn history (up to last 10 messages of the current active session)
        for h in (history or [])[-10:]:
            messages.append({
                "role": "user" if h.role == "user" else "assistant",
                "content": h.content
            })

        messages.append({
            "role": "user",
            "content": f"{context_prompt}\nUser Question: {user_message}"
        })

        payload = {
            "model": model,
            "messages": messages,
            "temperature": 0.4,
            "max_tokens": 2048,
            "response_format": {"type": "json_object"}
        }

        resp_data = self._execute_api_call(api_key, payload)

        choices = resp_data.get("choices", [])
        if not choices:
            raise ValueError("No choices returned from OpenAI API")

        raw_text = choices[0].get("message", {}).get("content", "")
        parsed_data = self._extract_json_response(raw_text)

        reply_text = parsed_data.get("message") or parsed_data.get("response") or raw_text
        expression = parsed_data.get("expression", "speaking")
        topics = parsed_data.get("topics", [])
        if not isinstance(topics, list):
            topics = []

        viz_required = bool(parsed_data.get("visualization_required", False))
        viz_intent = parsed_data.get("visualization_intent")

        return CompanionResponse(
            bot_name=bot_name,
            message=reply_text,
            expression=expression,
            visualization=None,
            visualization_required=viz_required,
            visualization_intent=viz_intent,
            topics=topics,
            recommended_problems=[],
            source_engine="openai"
        )
